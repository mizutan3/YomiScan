CONJUGATION_PATTERNS = {
    'った$': ['る', 'う'],     # 走った → 走る / 買った → 買う
    'んだ$': ['ぬ', 'ぶ', 'む'], # 死んだ → 死ぬ / 飛んだ → 飛ぶ / 読んだ → 読む
    'いだ$': ['ぐ'],           # 泳いだ → 泳ぐ
    'いた$': ['く'],           # 書いた → 書く
    'した$': ['す'],           # 話した → 話す
    'て$': [''],              # 食べて → 食べる
    'た$': [''],              # 食べた → 食べる
    'ない$': [''],            # 食べない → 食べる
    'ます$': [''],            # 食べます → 食べる
    'ましょう$': [''],        # 食べましょう → 食べる
}